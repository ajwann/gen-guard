"""Decide whether a file Claude is about to edit is generated, and where its source is."""
from __future__ import annotations

import fnmatch
import json
import os
import re
from pathlib import Path, PurePosixPath
from typing import Optional

import hookio

PLUGIN = "gen-guard"

DEFAULTS = {
    "mode": "deny",            # deny | ask | warn
    "allow": [],               # globs (project-relative) that may always be edited
    "extra_generated": [],     # extra globs to treat as generated
    "check_headers": True,
    "header_bytes": 2048,
}

# lockfile name -> command that regenerates it
LOCKFILES = {
    "package-lock.json": "npm install",
    "npm-shrinkwrap.json": "npm install",
    "pnpm-lock.yaml": "pnpm install",
    "yarn.lock": "yarn install",
    "bun.lockb": "bun install",
    "bun.lock": "bun install",
    "poetry.lock": "poetry lock",
    "uv.lock": "uv lock",
    "Pipfile.lock": "pipenv lock",
    "pdm.lock": "pdm lock",
    "Cargo.lock": "cargo update -p <crate> (or cargo build)",
    "go.sum": "go mod tidy",
    "Gemfile.lock": "bundle install",
    "composer.lock": "composer update <package>",
    "flake.lock": "nix flake update",
    "Package.resolved": "swift package resolve",
    "mix.lock": "mix deps.get",
    "pubspec.lock": "dart pub get",
}

# (glob, why) - matched against the project-relative posix path
PATH_RULES = [
    ("node_modules/**", "installed dependency (node_modules)"),
    ("**/node_modules/**", "installed dependency (node_modules)"),
    ("vendor/**", "vendored dependency"),
    (".venv/**", "virtualenv contents"),
    ("**/site-packages/**", "installed dependency (site-packages)"),
    ("dist/**", "build output (dist/)"),
    ("**/dist/**", "build output (dist/)"),
    (".next/**", "build output (.next/)"),
    ("target/**", "build output (target/)"),
    ("**/__generated__/**", "generated directory"),
    ("**/__pycache__/**", "bytecode cache"),
    ("*.egg-info/**", "packaging metadata"),
    ("**/*.pb.go", "protobuf output"),
    ("**/*.pb.h", "protobuf output"),
    ("**/*.pb.cc", "protobuf output"),
    ("**/*_pb2.py", "protobuf output"),
    ("**/*_pb2.pyi", "protobuf output"),
    ("**/*_pb2_grpc.py", "protobuf output"),
    ("**/*.min.js", "minified bundle"),
    ("**/*.min.css", "minified bundle"),
    ("**/*.g.dart", "build_runner output"),
    ("**/*.freezed.dart", "build_runner output"),
    ("**/zz_generated*.go", "Kubernetes code-generator output"),
    ("**/*.Designer.cs", "designer-generated code"),
]

HEADER_RE = re.compile(
    r"(?i)(\bdo not edit\b|@generated\b|\bauto-?generated\b|\bcode generated by\b|"
    r"\bthis file (?:is|was|has been) (?:automatically |auto-)?generated\b|"
    r"\bgenerated by .{0,60}\b(?:do not|don't) (?:edit|modify)\b)"
)
GO_GENERATE_RE = re.compile(r"^//go:generate\s+(.+)$", re.M)
PROTO_STEM_RE = re.compile(r"(.+?)(?:\.pb\.(?:go|h|cc)|_pb2(?:_grpc)?\.pyi?)$")


def _globmatch(rel: str, pattern: str) -> bool:
    """fnmatch with `**/` also matching zero directories."""
    if fnmatch.fnmatchcase(rel, pattern):
        return True
    if pattern.startswith("**/") and fnmatch.fnmatchcase(rel, pattern[3:]):
        return True
    return False


def target_path(event: dict) -> Optional[str]:
    ti = event.get("tool_input") or {}
    return ti.get("file_path") or ti.get("notebook_path")


def rel_to(project: Path, path: Path) -> Optional[str]:
    try:
        return PurePosixPath(path.resolve().relative_to(project.resolve())).as_posix()
    except ValueError:
        return None


def gitattributes_generated(project: Path, rel: str) -> bool:
    ga = project / ".gitattributes"
    if not ga.is_file():
        return False
    hit = False
    try:
        lines = ga.read_text(errors="replace").splitlines()
    except OSError:
        return False
    for line in lines:
        parts = line.strip().split()
        if len(parts) < 2 or parts[0].startswith("#"):
            continue
        pat, attrs = parts[0], parts[1:]
        state = None
        for a in attrs:
            if a in ("linguist-generated", "linguist-generated=true"):
                state = True
            elif a in ("-linguist-generated", "linguist-generated=false", "!linguist-generated"):
                state = False
        if state is None:
            continue
        if "/" not in pat.rstrip("/"):
            matched = fnmatch.fnmatchcase(PurePosixPath(rel).name, pat) or _globmatch(rel, "**/" + pat)
        else:
            p = pat.lstrip("/")
            matched = _globmatch(rel, p + "**" if p.endswith("/") else p)
        if matched:
            hit = state  # last match wins, as in git
    return hit


def header_marker(path: Path, nbytes: int) -> Optional[str]:
    try:
        with open(path, "rb") as f:
            head = f.read(nbytes).decode("utf-8", errors="replace")
    except OSError:
        return None
    for line in head.splitlines()[:15]:
        if HEADER_RE.search(line):
            return line.strip()[:200]
    return None


def _walk_find(project: Path, name: str, limit: int = 4000) -> list[str]:
    found, seen = [], 0
    skip = {".git", "node_modules", ".venv", "venv", "dist", "target", "__pycache__", "vendor"}
    for root, dirs, files in os.walk(project):
        dirs[:] = [d for d in dirs if d not in skip and not d.startswith(".")]
        seen += len(files)
        if name in files:
            found.append(PurePosixPath(Path(root, name).relative_to(project)).as_posix())
        if seen > limit or len(found) >= 3:
            break
    return found


def source_hints(project: Path, path: Path, rel: str) -> list[str]:
    hints: list[str] = []
    name = path.name
    if name in LOCKFILES:
        hints.append(f"Regenerate it with `{LOCKFILES[name]}` after changing the manifest.")
    m = PROTO_STEM_RE.match(name)
    if m:
        protos = _walk_find(project, m.group(1) + ".proto")
        hints.append("Source: " + ", ".join(protos) if protos else f"Source is likely {m.group(1)}.proto.")
    if path.suffix == ".go" and path.parent.is_dir():
        directives = []
        for sib in sorted(path.parent.glob("*.go"))[:200]:
            try:
                directives += [f"{sib.name}: //go:generate {d}" for d in GO_GENERATE_RE.findall(sib.read_text(errors="replace"))]
            except OSError:
                continue
        if directives:
            hints.append("Generator directives in this package: " + "; ".join(directives[:5]) + " (run `go generate ./...`).")
    if rel and (rel.startswith("dist/") or "/dist/" in rel):
        pkg = project / "package.json"
        try:
            scripts = json.loads(pkg.read_text()).get("scripts", {}) if pkg.is_file() else {}
        except (OSError, ValueError):
            scripts = {}
        if "build" in scripts:
            hints.append(f"Edit the sources and rebuild with the `build` script (`{scripts['build']}`).")
    return hints


def classify(project: Path, path: Path, cfg: dict) -> Optional[dict]:
    """Return {'why': ..., 'hints': [...]} if path is generated, else None."""
    rel = rel_to(project, path)
    key = rel if rel is not None else path.as_posix()
    if any(_globmatch(key, g) for g in cfg.get("allow") or []):
        return None
    why = None
    if path.name in LOCKFILES:
        why = "lockfile"
    if why is None and rel is not None:
        for glob, reason in PATH_RULES + [(g, "matches extra_generated") for g in cfg.get("extra_generated") or []]:
            if _globmatch(rel, glob):
                why = reason
                break
    if why is None and rel is not None and gitattributes_generated(project, rel):
        why = "marked linguist-generated in .gitattributes"
    if why is None and cfg.get("check_headers", True) and path.is_file():
        marker = header_marker(path, int(cfg.get("header_bytes", 2048)))
        if marker:
            why = f"its header says: {marker!r}"
    if why is None:
        return None
    return {"why": why, "rel": key, "hints": source_hints(project, path, rel or "")}


def handle(event: dict) -> Optional[dict]:
    if event.get("hook_event_name") != "PreToolUse":
        return None
    target = target_path(event)
    if not target:
        return None
    project = hookio.project_dir(event)
    path = Path(target)
    if not path.is_absolute():
        path = Path(event.get("cwd") or project) / path
    cfg = hookio.load_config(PLUGIN, project, DEFAULTS)
    verdict = classify(project, path, cfg)
    if not verdict:
        return None
    msg = [f"gen-guard: {verdict['rel']} looks generated ({verdict['why']}). A hand edit here is "
           "overwritten the next time it is regenerated."]
    msg += verdict["hints"]
    msg.append(f"If a hand edit is really intended, the path can be added to \"allow\" in "
               f".claude/{PLUGIN}.json.")
    text = " ".join(msg)
    mode = cfg.get("mode", "deny")
    if mode == "warn":
        return hookio.context("PreToolUse", text)
    if mode == "ask":
        out = hookio.deny(text)
        out["hookSpecificOutput"]["permissionDecision"] = "ask"
        return out
    return hookio.deny(text)
