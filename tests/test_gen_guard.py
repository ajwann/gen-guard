import json

from conftest import run_hook
from gen_guard.core import handle


def edit(project, rel, tool="Edit"):
    return {"hook_event_name": "PreToolUse", "cwd": str(project), "tool_name": tool,
            "tool_input": {"file_path": str(project / rel), "old_string": "a", "new_string": "b"}}


def decision(out):
    return (out or {}).get("hookSpecificOutput", {}).get("permissionDecision")


def test_plain_source_file_is_allowed(project):
    (project / "app.py").write_text("print('hi')\n")
    assert handle(edit(project, "app.py")) is None


def test_lockfile_denied_with_regen_command(project):
    (project / "pnpm-lock.yaml").write_text("lockfileVersion: 9\n")
    out = handle(edit(project, "pnpm-lock.yaml"))
    assert decision(out) == "deny"
    assert "pnpm install" in out["hookSpecificOutput"]["permissionDecisionReason"]


def test_header_marker_detected(project):
    (project / "models.go").write_text("// Code generated by sqlc. DO NOT EDIT.\npackage db\n")
    (project / "gen.go").write_text("package db\n//go:generate sqlc generate\n")
    out = handle(edit(project, "models.go"))
    reason = out["hookSpecificOutput"]["permissionDecisionReason"]
    assert decision(out) == "deny"
    assert "DO NOT EDIT" in reason and "sqlc generate" in reason


def test_protobuf_points_to_proto(project):
    (project / "api").mkdir()
    (project / "api" / "user.proto").write_text("syntax = 'proto3';\n")
    (project / "user_pb2.py").write_text("# stub\n")
    out = handle(edit(project, "user_pb2.py"))
    assert "api/user.proto" in out["hookSpecificOutput"]["permissionDecisionReason"]


def test_gitattributes_linguist_generated(project):
    (project / ".gitattributes").write_text("schema/*.ts linguist-generated\nschema/keep.ts -linguist-generated\n")
    (project / "schema").mkdir()
    (project / "schema" / "types.ts").write_text("export {}\n")
    (project / "schema" / "keep.ts").write_text("export {}\n")
    assert decision(handle(edit(project, "schema/types.ts"))) == "deny"
    assert handle(edit(project, "schema/keep.ts")) is None


def test_dist_with_build_script_hint(project):
    (project / "package.json").write_text(json.dumps({"scripts": {"build": "tsc -p ."}}))
    out = handle(edit(project, "dist/index.js", tool="Write"))
    assert "tsc -p ." in out["hookSpecificOutput"]["permissionDecisionReason"]


def test_allow_override_and_modes(project):
    (project / ".claude").mkdir()
    (project / "yarn.lock").write_text("")
    cfg = project / ".claude" / "gen-guard.json"
    cfg.write_text(json.dumps({"allow": ["yarn.lock"]}))
    assert handle(edit(project, "yarn.lock")) is None
    cfg.write_text(json.dumps({"mode": "warn"}))
    out = handle(edit(project, "yarn.lock"))
    assert "additionalContext" in out["hookSpecificOutput"] and decision(out) is None
    cfg.write_text(json.dumps({"mode": "ask"}))
    assert decision(handle(edit(project, "yarn.lock"))) == "ask"


def test_notebook_and_relative_path(project):
    (project / "nb").mkdir()
    ev = {"hook_event_name": "PreToolUse", "cwd": str(project), "tool_name": "NotebookEdit",
          "tool_input": {"notebook_path": "node_modules/x/a.ipynb"}}
    assert decision(handle(ev)) == "deny"


def test_new_file_without_marker_is_fine(project):
    assert handle(edit(project, "src/new.ts", tool="Write")) is None


def test_broken_config_fails_open_to_defaults(project, isolated):
    (project / ".claude").mkdir()
    (project / ".claude" / "gen-guard.json").write_text("{nope")
    (project / "go.sum").write_text("")
    assert decision(handle(edit(project, "go.sum"))) == "deny"


def test_script_end_to_end_and_garbage_input(project, isolated):
    (project / "Cargo.lock").write_text("")
    out = run_hook(edit(project, "Cargo.lock"), isolated)
    assert decision(out) == "deny"
    import subprocess, sys
    from conftest import ROOT
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "hook.py")], input="not json",
                       capture_output=True, text=True)
    assert r.returncode == 0 and r.stdout == ""
